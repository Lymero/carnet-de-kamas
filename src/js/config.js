/**
 * @file Application-wide constants.
 *
 * Everything that is a "magic value" elsewhere lives here, so behaviour can be
 * tuned in one place. Nothing in this file touches the DOM or the network.
 */

/** Trade categories, as stored in the database. */
export const CATEGORY = Object.freeze({
  CRAFT: "craft",
  RESALE: "resale",
});

/** Human labels for each category, as shown in the UI. */
export const CATEGORY_LABEL = Object.freeze({
  [CATEGORY.CRAFT]: "Craft/FM",
  [CATEGORY.RESALE]: "Achat/revente",
});

/** Version written on every trade document; bump when the shape changes (see docs/DATA-MODEL.md). */
export const SCHEMA_VERSION = 1;

/** Longest item name accepted (in-game names are well under this). */
export const ITEM_NAME_MAX = 200;

/** Database paths. `trades` is a collection, `settings/prices` a single document. */
export const DB_PATHS = Object.freeze({
  TRADES: "trades",
  PRICES: "settings/prices",
});

/** Views reachable through the URL hash (#en-cours, #historique, #analyse). */
export const VIEWS = Object.freeze(["en-cours", "historique", "analyse"]);

/** Root of the local server's data API (server/app.js), relative to the page. */
export const LOCAL_API_URL = "api/";

/** Relative URL of the item catalog generated by scripts/build_catalog.py. */
export const CATALOG_URL = "data/dofus-data.json";

/** An open trade listed for at least this many days is flagged as slow. */
export const SLOW_SALE_DAYS = 14;

/** How long to wait for the database before telling the user it is unreachable. */
export const LOAD_TIMEOUT_MS = 10_000;

/** Autocomplete sizing: suggestions shown in total, and how many may come from the user's own history. */
export const AUTOCOMPLETE = Object.freeze({ LIMIT: 10, OWN_LIMIT: 5, MIN_QUERY: 2 });

/** Number of months shown in the monthly profit chart. */
export const CHART_MONTHS = 12;

/** Retry policy for transient database errors. */
export const RETRY = Object.freeze({ ATTEMPTS: 4, BASE_DELAY_MS: 400, JITTER_MS: 300 });
